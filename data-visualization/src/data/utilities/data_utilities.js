export const default_log_options = (
  name,
  destination = './data_loaders.js.log',
  level = process.env.BUILD_ENV === 'production' ? 'warn' : 'debug',
) => ({
  name: name,
  level: level,
  sync: false,
  timestamp: pino.stdTimeFunctions.isoTime,
  transport: {
    target: 'pino-pretty',
    options: {
      // colorize: true,
      destination: destination,
      translateTime: 'yyyy-mm-dd HH:MM:ss.l',
    },
  },
})

let globalFetchQueue = Promise.resolve()

/**
 * Send an HTTP request to a URL API with some basic error handling and logging.
 *
 * @param {string} url - The endpoint url.
 * @param {number} [sleep=0] - The number of milliseconds to sleep before sending the request to avoid rate limiting.
 * @param {Object} [header={}] - An object containing additional headers to include in the request.
 * @param {pino.Logger} [logger=pino(default_log_options('fetch url utility'))] - A pino logger instance.
 * @returns {Promise<Object|null>} A promise resolving to a dictionary (object) of the request response if successful, or null.
 */
export async function handleFetchJson(
  url,
  sleep = 0,
  header,
  logger = pino(default_log_options('fetch url utility')),
) {
  logger.info(`HTTP request with: ${url}`)

  const executeFetch = async () => {
    if (sleep > 0) {
      await new Promise((resolve) => setTimeout(resolve, sleep))
    }

    try {
      const response = await fetch(url, {
        headers: {
          Accept: 'application/json',
          ...header,
        },
      })

      const data = await response.json()
      logger.debug(`response: ${JSON.stringify(data)}`)

      if (!response.ok) {
        // Emulate response.raise_for_status()
        throw new Error(
          `HTTP error! status: ${response.status} error: ${response.error}`,
        )
      }

      return data
    } catch (err) {
      if (err.message && err.message.startsWith('HTTP error')) {
        logger.error(`HTTP error occurred: ${err}; cause: ${err.cause}`)
      } else {
        logger.error(`Unknown error occurred: ${err}; cause: ${err.cause}`)
      }
      return null
    }
  }

  globalFetchQueue = globalFetchQueue.then(executeFetch).catch(() => null)
  return globalFetchQueue
}

/**
 * Fetch a URL and return its parsed JSON response
 *
 * @param {string} url - the URL to fetch
 * @returns {Promise<Object>} a promise resolving to the parsed JSON response
 */
export async function fetchJson(url) {
  const response = await fetch(url)
  if (!response.ok) throw new Error(`fetch failed: ${response.status}`)
  return await response.json()
}

/**
 * Fetch a URL and return its raw response text (CSV body)
 *
 * @param {string} url - the URL to fetch
 * @returns {Promise<string>} a promise resolving to the response body text
 */
export async function fetchCsv(url) {
  const response = await fetch(url)
  if (!response.ok) throw new Error(`fetch failed: ${response.status}`)
  return await response.text()
}
/**
 * Anonymize a text entry
 *
 * @returns {string} anonymized entry
 */
export function anonymizeEntry() {
  // return Math.random().toString(36).substring(2, 15)

  return randomBytes(16).toString('hex')
}

/**
 * (Pseudo)Anonymize a text entry based on existing dictionary values
 *
 * @param {string} entry - a text entry
 * @param {Map} dictionary - a mapping of entries to anonymized entries
 * @param {string} [type='human'] - the type of name to generate; based on high fantasy races
 * @returns {string} anonymized entry
 */
export function pseudoanonymizeEntry(entry, dictionary, type = 'human') {
  if (!dictionary.has(entry)) {
    dictionary.set(
      entry,
      nameByRace(type, {
        gender: Math.floor(Math.random() * 2) ? 'male' : 'female',
        allowMultipleNames: Math.floor(Math.random() * 2) ? true : false,
      }),
    )
  }
  return dictionary.get(entry)
}

/**
 * Filter out empty/undefined/zero values from an array
 *
 * @param {Array} data - the array (or array-like range) to filter
 * @returns {Array} the filtered array
 */
export function filterEmptyArray(data) {
  return filter(
    // use array substring for (headerless) ranges?
    data,
    (d) => typeof d !== 'undefined' && d !== 0 && d !== '',
  )
}

/**
 * Converts a string to lowercase, except for uppercase acronyms.
 * Preserves the case of words that contain no lowercase letters.
 * Initially generated by `Gemini 3 Pro (low)`
 *
 * @param {string} str - The input string
 * @returns {string} The processed string
 */
export function toLowerPreservingAcronyms(str) {
  if (!str) return str
  // Match chunks of words/numbers (including accents) to process them individually
  // This allows handling hyphenated words like "Micro-USB" correctly
  return str.replace(/[\w\u00C0-\u00FF]+/g, (word) => {
    // If the word contains ANY lowercase letter, convert it to lowercase
    // Otherwise (all caps, numbers, or symbols), keep it as is
    return /[a-z]/.test(word) ? word.toLowerCase() : word
  })
}

/**
 * Set each cell's column key to the text value found in a given header row,
 * mutating the worksheet in place.
 *
 * @param {ExcelJS.Workbook} workbook - the workbook containing the worksheet
 * @param {number} sheetNumber - the index of the worksheet to use
 * @param {number} [rowNumber=0] - the index of the row containing the column headers
 * @returns {void}
 */
export const mapRowToColumnKeys = (workbook, sheetNumber, rowNumber = 0) =>
  workbook.worksheets[sheetNumber]._rows[rowNumber].eachCell((cell) => {
    cell._column.key = cell.text
  })

/**
 * Convert an array of ExcelJS row objects into plain JS objects keyed by
 * each cell's column key (see mapRowToColumnKeys)
 *
 * @param {ExcelJS.Row[]} rows - the rows to convert
 * @returns {Object[]} an array of plain objects, one per row
 */
export const rowsToObjectArray = (rows) =>
  rows
    .map((row) =>
      row._cells
        .map((cell) => [cell._column.key, cell.text])
        .filter((d) => !!d),
    )
    .map((row) => Object.fromEntries(row))
