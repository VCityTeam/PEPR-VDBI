import { filter } from 'd3'
import { nameByRace } from 'fantasy-name-generator'
import pino from 'pino'

export const default_log_options = (name, destination = './data_loaders.js.log') => ({
  name: name,
  level: 'warn',
  sync: false,
  timestamp: pino.stdTimeFunctions.isoTime,
  transport: {
    target: 'pino-pretty',
    options: {
      // colorize: true,
      destination: destination,
      translateTime: 'yyyy-mm-dd HH:MM:ss.l',
    },
  },
})

/**
 * Send an HTTP request to a URL API with some basic error handling and logging.
 *
 * @param {string} url - The endpoint url.
 * @param {number} [sleep=0.2] - The number of seconds to sleep before sending the request to avoid rate limiting.
 * @param {string} accept - The mimetype accept header.
 * @param {pino.Logger} logger - A pino logger instance.
 * @returns {Promise<Object|null>} A promise resolving to a dictionary (object) of the request response if successful, or null.
 */
let globalFetchQueue = Promise.resolve()

export async function handleFetchJson(
  url,
  sleep = 0,
  logger = pino(default_log_options('fetch url utility')),
) {
  logger.info(`HTTP request with: ${url}`)

  const executeFetch = async () => {
    if (sleep > 0) {
      await new Promise((resolve) => setTimeout(resolve, sleep * 1000))
    }

    try {
      const response = await fetch(url, {
        headers: {
          Accept: 'application/json',
        },
      })

      if (!response.ok) {
        // Emulate response.raise_for_status()
        throw new Error(`HTTP error! status: ${response.status}`)
      }

      const data = await response.json()
      logger.debug(`${url} response: ${data}`)
      return data
    } catch (err) {
      if (err.message && err.message.startsWith('HTTP error')) {
        logger.error(`HTTP error occurred: ${err}`)
      } else {
        logger.error(`Other error occurred: ${err}; cause: ${err.cause}`)
      }
      return null
    }
  }

  globalFetchQueue = globalFetchQueue.then(executeFetch).catch(() => null)
  return globalFetchQueue
}

/**
 * Anonymize a text entry
 *
 * @returns {string} anonymized entry
 */
export function anonymizeEntry() {
  return Math.random().toString(36).substring(2, 15)
}

/**
 * (Pseudo)Anonymize a text entry based on existing dictionary values
 *
 * @param {string} entry - a text entry
 * @param {Map} dictionary - a mapping of entries to anonymized entries
 * @param {string} type - the type of name to generate; based on high fantasy races
 * @returns {string} anonymized entry
 */
export function pseudoanonymizeEntry(entry, dictionary, type = 'human') {
  if (!dictionary.has(entry)) {
    dictionary.set(
      entry,
      nameByRace(type, {
        gender: Math.floor(Math.random() * 2) ? 'male' : 'female',
        allowMultipleNames: Math.floor(Math.random() * 2) ? true : false,
      }),
    )
  }
  return dictionary.get(entry)
}

export function filterEmptyArray(data) {
  return filter(
    // use array substring for (headerless) ranges?
    data,
    (d) => typeof d !== 'undefined' && d !== 0 && d !== '',
  )
}

/**
 * Converts a string to lowercase, except for uppercase acronyms.
 * Preserves the case of words that contain no lowercase letters.
 * Initially generated by `Gemini 3 Pro (low)`
 *
 * @param {string} str - The input string
 * @returns {string} The processed string
 */
export function toLowerPreservingAcronyms(str) {
  if (!str) return str
  // Match chunks of words/numbers (including accents) to process them individually
  // This allows handling hyphenated words like "Micro-USB" correctly
  return str.replace(/[\w\u00C0-\u00FF]+/g, (word) => {
    // If the word contains ANY lowercase letter, convert it to lowercase
    // Otherwise (all caps, numbers, or symbols), keep it as is
    return /[a-z]/.test(word) ? word.toLowerCase() : word
  })
}

export const mapRowToColumnKeys = (workbook, sheetNumber, rowNumber = 0) =>
  workbook.worksheets[sheetNumber]._rows[rowNumber].eachCell((cell) => {
    cell._column.key = cell.text
  })

export const rowsToObjectArray = (rows) =>
  rows
    .map((row) =>
      row._cells
        .map((cell) => [cell._column.key, cell.text])
        .filter((d) => !!d),
    )
    .map((row) => Object.fromEntries(row))
